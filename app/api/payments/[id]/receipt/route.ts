import { NextRequest, NextResponse } from "next/server";
import { db } from "../../../../../src/prisma/db";
import { getSessionUserId } from "../../../../lib/auth";
import { getSupabaseStorage } from "../../../../lib/supabase-storage";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

type RouteProps = {
  params: Promise<{ id: string }>;
};

const ALLOWED_TYPES = [
  "application/pdf",
  "image/jpeg",
  "image/png",
];

export async function GET(
  _request: NextRequest,
  { params }: RouteProps
) {
  const userId = await getSessionUserId();

  if (!userId) {
    return new NextResponse("Unauthorized", { status: 401 });
  }

  const user = await db.orm.public.AppUser.first({
    id: userId,
  });

  if (!user || !user.isActive) {
    return new NextResponse("Unauthorized", { status: 401 });
  }

  const { id } = await params;
  const paymentId = Number(id);

  if (!Number.isSafeInteger(paymentId) || paymentId <= 0) {
    return new NextResponse("Invalid payment", { status: 400 });
  }

  const payment = await db.orm.public.Payment.first({
    id: paymentId,
  });

  if (
    !payment ||
    !payment.receiptFilePath ||
    !payment.receiptMimeType
  ) {
    return new NextResponse("Receipt not found", {
      status: 404,
    });
  }

  const storagePath = payment.receiptFilePath;
  const mimeType = payment.receiptMimeType;

  // Only allow receipt paths generated by our uploader.
  if (
    !/^receipts\/[0-9a-f-]{36}\.(pdf|jpg|png)$/.test(
      storagePath
    ) ||
    !ALLOWED_TYPES.includes(mimeType)
  ) {
    return new NextResponse("Receipt not available", {
      status: 404,
    });
  }

  try {
    const { data, error } =
      await getSupabaseStorage().download(storagePath);

    if (error || !data) {
      console.error(
        "Unable to download payment receipt:",
        error
      );

      return new NextResponse("Receipt not available", {
        status: 404,
      });
    }

    const bytes = new Uint8Array(
      await data.arrayBuffer()
    );

    const originalName =
      payment.receiptFileName || "payment-receipt";

    const safeName =
      originalName
        .replace(/[^\w.\- ]/g, "_")
        .slice(0, 150) || "payment-receipt";

    return new NextResponse(bytes, {
      status: 200,
      headers: {
        "Content-Type": mimeType,
        "Content-Disposition":
          `attachment; filename="${safeName}"`,
        "Content-Length": String(bytes.length),
        "Cache-Control": "private, no-store",
        "X-Content-Type-Options": "nosniff",
      },
    });
  } catch (error) {
    console.error(
      "Error downloading payment receipt:",
      error
    );

    return new NextResponse(
      "Unable to download receipt",
      { status: 500 }
    );
  }
}