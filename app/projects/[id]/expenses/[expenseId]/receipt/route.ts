import { db } from "../../../../../../src/prisma/db";
import { getSessionUserId } from "../../../../../lib/auth";
import { getSupabaseStorage } from "../../../../../lib/supabase-storage";
import { notFound } from "next/navigation";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

type RouteContext = {
  params: Promise<{
    id: string;
    expenseId: string;
  }>;
};

const ALLOWED_TYPES = [
  "application/pdf",
  "image/jpeg",
  "image/png",
];

export async function GET(
  _request: Request,
  { params }: RouteContext
) {
  // Only authenticated users can view receipts.
  const userId = await getSessionUserId();

  if (!userId) {
    return new Response("Unauthorized", {
      status: 401,
    });
  }

  // The user must still be active.
  const user = await db.orm.public.AppUser.first({
    id: userId,
  });

  if (!user || !user.isActive) {
    return new Response("Unauthorized", {
      status: 401,
    });
  }

  const { id, expenseId } = await params;

  const projectId = Number(id);
  const parsedExpenseId = Number(expenseId);

  if (
    !Number.isSafeInteger(projectId) ||
    projectId <= 0 ||
    !Number.isSafeInteger(parsedExpenseId) ||
    parsedExpenseId <= 0
  ) {
    notFound();
  }

  const expense = await db.orm.public.Expense.first({
    id: parsedExpenseId,
  });

  // The receipt must belong to this project.
  if (
    !expense ||
    expense.projectId !== projectId ||
    !expense.receiptFilePath ||
    !expense.receiptMimeType
  ) {
    notFound();
  }

  const storagePath = expense.receiptFilePath;
  const mimeType = expense.receiptMimeType;

  // Only allow receipt paths generated by our uploader.
  if (
    !/^receipts\/[0-9a-f-]{36}\.(pdf|jpg|png)$/.test(
      storagePath
    ) ||
    !ALLOWED_TYPES.includes(mimeType)
  ) {
    notFound();
  }

  try {
    // Download from the private Supabase bucket.
    const { data, error } =
      await getSupabaseStorage().download(storagePath);

    if (error || !data) {
      console.error("Unable to download project receipt:", error);
      notFound();
    }

    const bytes = new Uint8Array(
      await data.arrayBuffer()
    );

    return new Response(bytes, {
      status: 200,
      headers: {
        "Content-Type": mimeType,
        "Content-Disposition": "inline",
        "Cache-Control": "private, no-store",
        "X-Content-Type-Options": "nosniff",
      },
    });
  } catch (error) {
    // Preserve Next.js 404 responses.
    if (
      error &&
      typeof error === "object" &&
      "digest" in error &&
      error.digest === "NEXT_HTTP_ERROR_FALLBACK;404"
    ) {
      throw error;
    }

    console.error("Error reading project receipt:", error);

    return new Response("Unable to open receipt.", {
      status: 500,
    });
  }
}