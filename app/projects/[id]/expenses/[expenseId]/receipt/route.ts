import { db } from "../../../../../../src/prisma/db";
import { notFound } from "next/navigation";
import { readFile } from "node:fs/promises";
import path from "node:path";

export const runtime = "nodejs";

type RouteContext = {
  params: Promise<{
    id: string;
    expenseId: string;
  }>;
};

const ALLOWED_TYPES = [
  "application/pdf",
  "image/jpeg",
  "image/png",
];

export async function GET(
  _request: Request,
  { params }: RouteContext
) {
  const { id, expenseId } = await params;

  const projectId = Number(id);
  const parsedExpenseId = Number(expenseId);

  if (
    !Number.isInteger(projectId) ||
    projectId <= 0 ||
    !Number.isInteger(parsedExpenseId) ||
    parsedExpenseId <= 0
  ) {
    notFound();
  }

  const expense = await db.orm.public.Expense.first({
    id: parsedExpenseId,
  });

  if (
    !expense ||
    expense.projectId !== projectId ||
    !expense.receiptFilePath ||
    !expense.receiptMimeType
  ) {
    notFound();
  }

  const storedName = expense.receiptFilePath;

  // Only permit filenames generated by our upload function.
  if (
    !/^[0-9a-f-]{36}\.(pdf|jpg|png)$/.test(storedName) ||
    !ALLOWED_TYPES.includes(expense.receiptMimeType)
  ) {
    notFound();
  }

  const fullPath = path.join(
    process.cwd(),
    "storage",
    "receipts",
    storedName
  );

  let file: Buffer;

  try {
    file = await readFile(fullPath);
  } catch {
    notFound();
  }

  return new Response(new Uint8Array(file), {
    headers: {
      "Content-Type": expense.receiptMimeType,
      "Content-Disposition": "inline",
      "Cache-Control": "private, no-store",
      "X-Content-Type-Options": "nosniff",
    },
  });
}